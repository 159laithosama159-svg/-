export const NOVELS_STORAGE_KEY = 'sutoor_novels_state_v1';

export function createDefaultNovelsState(): NovelsPersistedState {
  return {
    customNovels: [],
    extraChaptersByNovel: {},
    favorites: ['novel_citadel_of_mirrors'],
    bookmarks: [],
    progress: {},
    readerSettings: { ...DEFAULT_READER_SETTINGS },
  };
}

export function loadNovelsState(): NovelsPersistedState {
  try {
    const raw = localStorage.getItem(NOVELS_STORAGE_KEY);
    if (!raw) return createDefaultNovelsState();
    const parsed = JSON.parse(raw) as Partial<NovelsPersistedState>;
    return {
      customNovels: Array.isArray(parsed.customNovels) ? parsed.customNovels : [],
      extraChaptersByNovel:
        parsed.extraChaptersByNovel && typeof parsed.extraChaptersByNovel === 'object'
          ? parsed.extraChaptersByNovel
          : {},
      favorites: Array.isArray(parsed.favorites) ? parsed.favorites : [],
      bookmarks: Array.isArray(parsed.bookmarks) ? parsed.bookmarks : [],
      progress: parsed.progress && typeof parsed.progress === 'object' ? parsed.progress : {},
      readerSettings: {
        theme: parsed.readerSettings?.theme || DEFAULT_READER_SETTINGS.theme,
        fontSizePx: Number(parsed.readerSettings?.fontSizePx) || DEFAULT_READER_SETTINGS.fontSizePx,
        lineHeight: Number(parsed.readerSettings?.lineHeight) || DEFAULT_READER_SETTINGS.lineHeight,
        flipSoundEnabled:
          typeof parsed.readerSettings?.flipSoundEnabled === 'boolean'
            ? parsed.readerSettings.flipSoundEnabled
            : true,
      },
    };
  } catch {
    return createDefaultNovelsState();
  }
}

export function saveNovelsState(state: NovelsPersistedState): void {
  try {
    localStorage.setItem(NOVELS_STORAGE_KEY, JSON.stringify(state));
  } catch {
    // ignore storage quota errors
  }
}

export function mergeAllNovels(state: NovelsPersistedState): NovelBook[] {
  const curatedWithExtras = CURATED_ARABIC_NOVELS.map((novel) => {
    const extras = state.extraChaptersByNovel[novel.id] || [];
    if (extras.length === 0) return novel;
    return {
      ...novel,
      chapters: [...novel.chapters, ...extras],
    };
  });
  return [...state.customNovels, ...curatedWithExtras];
}

export function computeNovelWordCount(novel: NovelBook): number {
  return novel.chapters.reduce((sum, ch) => {
    const words = (ch.content || '').trim().split(/\s+/).filter(Boolean).length;
    return sum + words;
  }, 0);
}

export function estimateReadingMinutes(wordCount: number): number {
  return Math.max(1, Math.ceil(wordCount / 180));
}

